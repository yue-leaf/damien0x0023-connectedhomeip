"""Convert CSA's published Matter mark to the LCD's small monochrome asset.

Requires Pillow. This is an asset preparation tool, not a firmware build step.
The Matter mark remains subject to CSA's trademark/logo usage guidelines.
"""

import argparse
import base64
import hashlib
import io
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image, ImageOps


SOURCE = "https://csa-iot.org/wp-content/uploads/2021/12/matter.svg"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--svg", type=Path, help="Use a previously downloaded copy of the source SVG")
    args = parser.parse_args()
    if args.svg:
        svg = args.svg.read_bytes()
    else:
        request = urllib.request.Request(SOURCE, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request, timeout=30) as response:
            svg = response.read()
    root = ET.fromstring(svg)
    embedded = root.find(".//{http://www.w3.org/2000/svg}image")
    png = base64.b64decode(embedded.attrib["{http://www.w3.org/1999/xlink}href"].split(",", 1)[1])
    image = Image.open(io.BytesIO(png)).convert("RGBA")
    background = Image.new("RGBA", image.size, "white")
    background.alpha_composite(image)
    image = background.convert("L")
    image = image.crop(ImageOps.invert(image).getbbox())
    image = ImageOps.contain(image, (160, 34), Image.Resampling.LANCZOS)
    canvas = Image.new("L", (160, 34), 255)
    canvas.paste(image, ((160 - image.width) // 2, (34 - image.height) // 2))
    data = []
    for y in range(34):
        for x in range(0, 160, 8):
            data.append(sum((1 << (7 - bit)) for bit in range(8) if canvas.getpixel((x + bit, y)) < 128))
    lines = [", ".join(f"0x{byte:02X}" for byte in data[start:start + 20]) for start in range(0, len(data), 20)]
    header = (
        "// Generated by tools/generate_matter_logo.py. Do not edit manually.\n"
        f"// Source: {SOURCE}\n"
        f"// Source SHA-256: {hashlib.sha256(svg).hexdigest()}\n"
        "// Matter is a CSA trademark; its logo is subject to CSA usage guidelines.\n"
        "#pragma once\n\n#include <stdint.h>\n\n"
        "constexpr int kMatterLogoWidth = 160;\nconstexpr int kMatterLogoHeight = 34;\n"
        "constexpr uint8_t kMatterLogoBitmap[] = {\n    " + ",\n    ".join(lines) + "\n};\n"
    )
    (Path(__file__).resolve().parents[1] / "src" / "MatterLogo.h").write_text(header, encoding="ascii")


if __name__ == "__main__":
    main()
